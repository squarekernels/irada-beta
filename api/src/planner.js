const tomorrow = () => {
  const date = new Date();
  date.setDate(date.getDate() + 1);
  return date.toISOString().slice(0, 10);
};

const nextWeek = () => {
  const date = new Date();
  date.setDate(date.getDate() + 7);
  return date.toISOString().slice(0, 10);
};

/**
 * Deterministic placeholder for the future AI planner.
 * Keep this function's response shape stable when replacing its internals.
 */
export async function createPlanPreview(input) {
  const normalized = input.toLowerCase();
  const tasks = [];

  if (normalized.includes('passport')) {
    tasks.push({
      title: 'Renew passport',
      notes: null,
      dueDate: nextWeek(),
      reminderAt: null,
      suggested: true,
      reason: 'Suggested from the trip timing in your note.',
    });
  }

  if (normalized.includes('grocer')) {
    tasks.push({
      title: 'Buy groceries',
      notes: null,
      dueDate: tomorrow(),
      reminderAt: `${tomorrow()}T09:00:00`,
      suggested: true,
      reason: normalized.includes('tomorrow') ? "Based on 'tomorrow'." : 'Suggested as a near-term errand.',
    });
  }

  if (normalized.includes('sara')) {
    tasks.push({
      title: 'Call Sara',
      notes: null,
      dueDate: nextWeek(),
      reminderAt: null,
      suggested: true,
      reason: normalized.includes('week') ? "Based on 'this week'." : 'Suggested from your note.',
    });
  }

  if (tasks.length === 0) {
    tasks.push({
      title: input.trim().replace(/[.!?]+$/, '').slice(0, 120),
      notes: null,
      dueDate: null,
      reminderAt: null,
      suggested: true,
      reason: 'Placeholder extraction from your note.',
    });
  }

  return {
    input,
    tasks,
    isStub: true,
    message: 'This plan was generated by the placeholder planner. No AI service was called.',
  };
}
